<?php

use dokuwiki\Extension\CLIPlugin;
use splitbrain\phpcli\Options;

/**
 * DokuWiki Plugin structodt (CLI Component)
 *
 * @license GPL 2 http://www.gnu.org/licenses/gpl-2.0.html
 * @author  Szymon Olewniczak <it@rid.pl>
 */
class cli_plugin_structodt extends CLIPlugin
{
    /** @var helper_plugin_structodt */
    protected $helper;

    /**
     * Initialize helper
     */
    public function __construct()
    {
        parent::__construct();
        $this->helper = plugin_load('helper', 'structodt');
    }

    /**
     * @inheritDoc
     */
    protected function setup(Options $options)
    {
        $options->setHelp('Maintenance and temporary file cleanup tools for the structodt plugin');

        $options->registerCommand(
            'cleanup',
            'Delete temporary files and directories generated by structodt'
        );

        $options->registerOption(
            'dry-run',
            'Only report what would be deleted, without modifying the filesystem',
            'd',
            false,
            'cleanup'
        );

        $options->registerOption(
            'older-than',
            'Only delete files/directories older than N minutes (default: 0 - deletes everything)',
            'm',
            'minutes',
            'cleanup'
        );
    }

    /**
     * @inheritDoc
     */
    protected function main(Options $options)
    {
        $cmd = $options->getCmd();
        switch ($cmd) {
            case 'cleanup':
                try {
                    $dryRun = (bool)$options->getOpt('dry-run');
                    $olderThan = (int)$options->getOpt('older-than', 0);
                    $this->cleanupTemp($dryRun, $olderThan);
                } catch (\Exception $e) {
                    $this->fatal($e);
                }
                break;

            default:
                $this->error('No valid command provided');
                echo $options->help();
                exit(1);
        }
    }

    /**
     * Clean up the structodt temporary directory
     *
     * @param bool $dryRun
     * @param int $olderThanMinutes
     * @return void
     * @throws \RuntimeException
     */
    protected function cleanupTemp(bool $dryRun, int $olderThanMinutes): void
    {
        global $conf;

        $baseDir = rtrim(!empty($conf['tmpdir']) ? $conf['tmpdir'] : sys_get_temp_dir(), '/') . '/structodt';

        if (!is_dir($baseDir)) {
            $this->info("Temporary directory $baseDir does not exist - nothing to clean up.");
            return;
        }

        if ($dryRun) {
            $this->notice('Running in dry-run mode - no files will be deleted.');
        }

        $now = time();
        $cutoffTime = $olderThanMinutes > 0 ? ($now - ($olderThanMinutes * 60)) : $now + 1;

        $items = @scandir($baseDir);
        if ($items === false) {
            throw new \RuntimeException("Unable to read directory: $baseDir");
        }

        $deletedFiles = 0;
        $deletedDirs = 0;
        $freedBytes = 0;
        $failed = 0;

        foreach ($items as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }

            $path = $baseDir . '/' . $item;
            $mtime = @filemtime($path) ?: 0;

            // Check element modification time
            if ($mtime > $cutoffTime) {
                continue;
            }

            $size = $this->calculateSize($path);

            if (is_dir($path)) {
                $this->info(sprintf('Directory: %s (%s, modified: %s)', $item, filesize_h($size), dformat($mtime)));

                if (!$dryRun) {
                    try {
                        if ($this->helper && method_exists($this->helper, 'rmdir_recursive')) {
                            $this->helper->rmdir_recursive($path);
                        } else {
                            $this->rmdirRecursive($path);
                        }
                        $deletedDirs++;
                        $freedBytes += $size;
                    } catch (\Exception $e) {
                        $failed++;
                        $this->error(sprintf('Failed to remove directory %s: %s', $item, $e->getMessage()));
                    }
                } else {
                    $deletedDirs++;
                    $freedBytes += $size;
                }
            } else {
                $this->info(sprintf('File: %s (%s, modified: %s)', $item, filesize_h($size), dformat($mtime)));

                if (!$dryRun) {
                    if (@unlink($path)) {
                        $deletedFiles++;
                        $freedBytes += $size;
                    } else {
                        $failed++;
                        $this->error(sprintf('Failed to remove file: %s', $item));
                    }
                } else {
                    $deletedFiles++;
                    $freedBytes += $size;
                }
            }
        }

        if ($failed > 0) {
            $this->warning(sprintf('Failed to remove %d item(s) (check filesystem permissions).', $failed));
        }

        $this->success(sprintf(
            'Done: removed %d file(s), %d director(y/ies). Freed: %s.',
            $deletedFiles,
            $deletedDirs,
            filesize_h($freedBytes)
        ));
    }

    /**
     * Calculate size of a file or directory recursively
     *
     * @param string $path
     * @return int
     */
    protected function calculateSize(string $path): int
    {
        if (!is_dir($path)) {
            return (int)@filesize($path);
        }

        $size = 0;
        try {
            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS)
            );
            foreach ($iterator as $file) {
                $size += $file->getSize();
            }
        } catch (\Exception $e) {
            // Ignore read errors for inaccessible files
        }
        return $size;
    }

    /**
     * Fallback recursive directory removal
     *
     * @param string $path
     * @return void
     */
    protected function rmdirRecursive(string $path): void
    {
        if (!is_dir($path)) return;
        $directory = new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS);
        $iterator = new \RecursiveIteratorIterator($directory, \RecursiveIteratorIterator::CHILD_FIRST);
        foreach ($iterator as $file) {
            if ($file->isDir()) {
                @rmdir($file->getRealPath());
            } else {
                @unlink($file->getRealPath());
            }
        }
        @rmdir($path);
    }
}